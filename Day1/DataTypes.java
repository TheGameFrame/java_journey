class DataTypes
{
    public static void main (String a[])
    {
        int num = 1;
        byte by = 127;
        short sh = 556;
        long lo = 5461l;
        double db = 6.5;
        float fl = 6.5f;
        char ch = 'b';
        boolean bl = true;

        System.out.println(num + by + sh + lo + db + fl);
        System.out.println(ch);
        System.out.println(bl);
    }
}
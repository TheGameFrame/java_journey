public class RelationalOperators {
    public static void main (String[] args) 
    {
       //Decimals (Double)
        double x = 8.8;
        double y = 9.5;

       boolean result = x >= y;
       System.out.println(result);


       
       //Integers
       int a = 8;
       int b = 6;
       boolean result2 = a >= b;
       System.out.println(result2);

    }}